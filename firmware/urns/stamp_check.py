def _tab(f):
    o = f * 5
    return int.from_bytes(_TAB[o:o + 5], "big")


def cost_to_fp(cost):
    v = int(float(cost) * COST_FP + 0.5) if cost > 0 else 0
    return v if v < _FP_CAP else _FP_CAP


def target_from_fp(fp):
    """32-byte big-endian target for a fixed-point cost. Cost 0 is 2^256, which
    does not fit; it is clamped to all-ones (every hash satisfies it)."""
    i, f = divmod(256 * COST_FP - fp, COST_FP)
    t = (_tab(f) << i) >> MANTISSA_BITS
    if t >= (1 << 256):
        return _MAX_TARGET
    return t.to_bytes(32, "big")


def stamp_valid(stamp, cost, material):
    """sha256(material + stamp) <= target(cost). Big-endian byte strings
    compare like the integers they encode."""
    return sha256(material + stamp) <= target_from_fp(cost_to_fp(cost))


def _lz_bits(d):
    """Leading zero bits of a byte string (no int.bit_length on MicroPython)."""
    n = 0
    for c in d:
        if c == 0:
            n += 8
            continue
        while not c & 0x80:
            c <<= 1
            n += 1
        break
    return n


def stamp_value(material, stamp):
    """Full fixed-point value as the reference computes it (leading zeros plus
    the mantissa climb through TAB), returned as a float like the reference."""
    d = sha256(material + stamp)
    lz = _lz_bits(d)
    if lz >= 256:
        return 256.0
    bl = 256 - lz
    hn = int.from_bytes(d, "big")
    nb = MANTISSA_BITS + 1
    mn = (hn >> (bl - nb)) if bl > nb else (hn << (nb - bl))
    lo, hi = 0, COST_FP          # bisect_right(TAB, mn)
    while lo < hi:
        mid = (lo + hi) >> 1
        if mn < _tab(mid):
            hi = mid
        else:
            lo = mid + 1
    return (((lz + 1) << COST_FP_BITS) - lo) / COST_FP
